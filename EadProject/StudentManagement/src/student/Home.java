    public boolean isEmptyStudent() 
    {
        if (jTextField7.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Student name is missing");
            return false;
        }
        if (jDateChooser2.getDate() == null) {
            JOptionPane.showMessageDialog(this, "Student date of birth is missing");
            return false;
        }
         if (jDateChooser2.getDate().compareTo(new Date())> 0)
         {
            JOptionPane.showMessageDialog(this,"No Student from the future are allowed ");
            return false;
         }
        if (jTextField8.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Student Email is missing");
            return false;
        }
        if (!jTextField8.getText().matches("^.+@.+\\..+$")) {
            JOptionPane.showMessageDialog(this, "Invalid email Address!");
            return false;
        }
        if (jTextField9.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Student Contact Number is missing");
            return false;
        }
        if (jTextField9.getText().length() >= 12) {
            JOptionPane.showMessageDialog(this, "Phone Number too Long!");
            return false;
        }
        if (jTextField10.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Student Address is missing");
            return false;
        }
        if(imagepath==null)
        {
            JOptionPane.showMessageDialog(this, "Student Image is missing");
            return false;
        }
        return true;
    }
    
 
